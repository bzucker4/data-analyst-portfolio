"""Run the SQL in queries.sql against vehicles.csv, save charts, and write results.md.

Run:  python analysis.py
"""
import re
import sqlite3
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

HERE = Path(__file__).parent
CHARTS = HERE / "charts"
BLUE, ORANGE, GREY = "#1F3A5F", "#D9822B", "#9AA5B1"
SKIP_IN_RESULTS = {"daily_lot_inventory"}  # 365 rows; used for a chart only
plt.rcParams.update({"axes.spines.top": False, "axes.spines.right": False, "font.size": 10})


def load_queries(path: Path) -> dict:
    """Split queries.sql into {name: sql} using the '-- name:' markers."""
    text = path.read_text()
    parts = re.split(r"^-- name:\s*(\w+)\s*$", text, flags=re.MULTILINE)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}


def md_table(df: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    divider = "|" + "|".join(["---"] * len(df.columns)) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([header, divider, *rows])


def bar_chart(df, x, y, title, ylabel, filename, fmt="%.1f", highlight=None):
    fig, ax = plt.subplots(figsize=(7, 4))
    colors = [ORANGE if (highlight and v == highlight) else BLUE for v in df[x]]
    bars = ax.bar(df[x], df[y], color=colors)
    ax.bar_label(bars, fmt=fmt, padding=3)
    ax.set_title(title, loc="left", fontweight="bold")
    ax.set_ylabel(ylabel)
    ax.set_ylim(0, df[y].max() * 1.15)
    fig.tight_layout()
    fig.savefig(CHARTS / filename, dpi=150)
    plt.close(fig)


def main() -> None:
    CHARTS.mkdir(exist_ok=True)
    conn = sqlite3.connect(":memory:")
    pd.read_csv(HERE / "data" / "vehicles.csv").to_sql("vehicles", conn, index=False)
    queries = load_queries(HERE / "queries.sql")
    results = {name: pd.read_sql_query(sql, conn) for name, sql in queries.items()}

    src = results["dwell_by_source"]
    bar_chart(src, "arrival_source", "avg_dwell_days", "Average dwell time by arrival source",
              "Days on lot", "dwell_by_source.png", highlight=src.iloc[0]["arrival_source"])

    dmg = results["dwell_by_damage"]
    bar_chart(dmg, "condition", "avg_dwell_days", "Average dwell time: damaged vs undamaged on arrival",
              "Days on lot", "dwell_by_damage.png", highlight="Damaged on arrival")

    combo = results["source_and_damage_combined"].pivot(
        index="arrival_source", columns="condition", values="avg_dwell_days"
    )[["No damage", "Damaged"]]
    fig, ax = plt.subplots(figsize=(7, 4))
    combo.plot(kind="bar", ax=ax, color=[BLUE, ORANGE], rot=0)
    for container in ax.containers:
        ax.bar_label(container, fmt="%.1f", padding=3)
    ax.set_title("Average dwell time by source and condition", loc="left", fontweight="bold")
    ax.set_ylabel("Days on lot")
    ax.set_xlabel("")
    ax.set_ylim(0, combo.values.max() * 1.15)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(CHARTS / "dwell_by_source_and_damage.png", dpi=150)
    plt.close(fig)

    daily = results["daily_lot_inventory"]
    daily["day"] = pd.to_datetime(daily["day"])
    steady = daily[daily["day"] >= "2025-02-01"]  # skip the ramp-up month: the lot starts empty
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(daily["day"], daily["vehicles_on_lot"], color=BLUE, linewidth=1.5)
    ax.axvspan(daily["day"].min(), pd.Timestamp("2025-02-01"), color=GREY, alpha=0.25, label="Ramp-up (lot starts empty)")
    ax.axhline(steady["vehicles_on_lot"].mean(), color=ORANGE, linestyle="--",
               label=f"Average after ramp-up: {steady['vehicles_on_lot'].mean():.0f}")
    ax.set_title("Vehicles on the lot, daily", loc="left", fontweight="bold")
    ax.set_ylabel("Vehicles on lot")
    ax.set_ylim(bottom=0)
    ax.legend(frameon=False, loc="lower right")
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(CHARTS / "daily_lot_inventory.png", dpi=150)
    plt.close(fig)

    lines = ["# Results (generated by analysis.py)\n"]
    for name, df in results.items():
        if name in SKIP_IN_RESULTS:
            continue
        lines += [f"## {name}\n", md_table(df), ""]
    (HERE / "results.md").write_text("\n".join(lines))
    print("Wrote charts/ and results.md")


if __name__ == "__main__":
    main()
