"""Run the SQL in queries.sql against the cycle count CSVs, save charts, and write results.md.

Run:  python analysis.py
"""
import re
import sqlite3
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

HERE = Path(__file__).parent
CHARTS = HERE / "charts"
BLUE, ORANGE, GREY = "#1F3A5F", "#D9822B", "#9AA5B1"
plt.rcParams.update({"axes.spines.top": False, "axes.spines.right": False, "font.size": 10})


def load_queries(path: Path) -> dict:
    """Split queries.sql into {name: sql} using the '-- name:' markers."""
    text = path.read_text()
    parts = re.split(r"^-- name:\s*(\w+)\s*$", text, flags=re.MULTILINE)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}


def md_table(df: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    divider = "|" + "|".join(["---"] * len(df.columns)) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([header, divider, *rows])


def bar_chart(df, x, y, title, ylabel, filename, highlight=(), fmt="%.1f%%"):
    fig, ax = plt.subplots(figsize=(7, 4))
    colors = [ORANGE if v in highlight else BLUE for v in df[x]]
    bars = ax.bar(df[x], df[y], color=colors)
    ax.bar_label(bars, fmt=fmt, padding=3)
    ax.set_title(title, loc="left", fontweight="bold")
    ax.set_ylabel(ylabel)
    ax.set_ylim(0, df[y].max() * 1.2)
    fig.tight_layout()
    fig.savefig(CHARTS / filename, dpi=150)
    plt.close(fig)


def main() -> None:
    CHARTS.mkdir(exist_ok=True)
    conn = sqlite3.connect(":memory:")
    pd.read_csv(HERE / "data" / "cycle_counts.csv").to_sql("cycle_counts", conn, index=False)
    pd.read_csv(HERE / "data" / "skus.csv").to_sql("skus", conn, index=False)
    queries = load_queries(HERE / "queries.sql")
    results = {name: pd.read_sql_query(sql, conn) for name, sql in queries.items()}

    by_cat = results["accuracy_by_category"]
    bar_chart(by_cat, "category", "exact_accuracy_pct", "Cycle count accuracy by category",
              "% of counts matching system", "accuracy_by_category.png",
              highlight=tuple(by_cat["category"].head(2)))

    by_cat_usd = by_cat.sort_values("abs_variance_usd", ascending=False)
    bar_chart(by_cat_usd, "category", "abs_variance_usd", "Dollar variance by category (absolute)",
              "USD", "variance_usd_by_category.png",
              highlight=tuple(by_cat_usd["category"].head(2)), fmt="$%.0f")

    by_shift = results["accuracy_by_shift"]
    bar_chart(by_shift, "shift", "exact_accuracy_pct", "Cycle count accuracy by shift",
              "% of counts matching system", "accuracy_by_shift.png", highlight=("Night",))

    monthly = results["monthly_trend"]
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(monthly["month"], monthly["exact_accuracy_pct"], color=BLUE, linewidth=2.5, label="All SKUs")
    ax.plot(monthly["month"], monthly["produce_pct"], color=ORANGE, linewidth=1.5, label="Produce")
    ax.plot(monthly["month"], monthly["dairy_pct"], color=GREY, linewidth=1.5, label="Dairy")
    ax.set_title("Monthly cycle count accuracy", loc="left", fontweight="bold")
    ax.set_ylabel("% of counts matching system")
    ax.set_ylim(0, 100)
    ax.legend(frameon=False)
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(CHARTS / "monthly_accuracy.png", dpi=150)
    plt.close(fig)

    lines = ["# Results (generated by analysis.py)\n"]
    for name, df in results.items():
        lines += [f"## {name}\n", md_table(df), ""]
    (HERE / "results.md").write_text("\n".join(lines))
    print("Wrote charts/ and results.md")


if __name__ == "__main__":
    main()
