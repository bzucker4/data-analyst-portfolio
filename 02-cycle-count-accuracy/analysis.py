"""Run the SQL in queries.sql against the cycle count data, save charts, and write results.md.

Run:  python analysis.py
"""
import re
import sqlite3
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

HERE = Path(__file__).parent
CHARTS = HERE / "charts"
BLUE, ORANGE = "#1F3A5F", "#D9822B"
plt.rcParams.update({"axes.spines.top": False, "axes.spines.right": False, "font.size": 10})


def load_queries(path: Path) -> dict:
    """Split queries.sql into {name: sql} using the '-- name:' markers."""
    text = path.read_text()
    parts = re.split(r"^-- name:\s*(\w+)\s*$", text, flags=re.MULTILINE)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}


def md_table(df: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    divider = "|" + "|".join(["---"] * len(df.columns)) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([header, divider, *rows])


def bar_chart(df, x, y, title, ylabel, filename, fmt="%.1f%%", highlight=None, ymin=0):
    fig, ax = plt.subplots(figsize=(7, 4))
    colors = [ORANGE if (highlight and v == highlight) else BLUE for v in df[x]]
    bars = ax.bar(df[x], df[y], color=colors)
    ax.bar_label(bars, fmt=fmt, padding=3)
    ax.set_title(title, loc="left", fontweight="bold")
    ax.set_ylabel(ylabel)
    ax.set_ylim(ymin, df[y].max() * 1.15)
    fig.tight_layout()
    fig.savefig(CHARTS / filename, dpi=150)
    plt.close(fig)


def main() -> None:
    CHARTS.mkdir(exist_ok=True)
    conn = sqlite3.connect(":memory:")
    pd.read_csv(HERE / "data" / "skus.csv").to_sql("skus", conn, index=False)
    pd.read_csv(HERE / "data" / "cycle_counts.csv").to_sql("cycle_counts", conn, index=False)
    queries = load_queries(HERE / "queries.sql")
    results = {name: pd.read_sql_query(sql, conn) for name, sql in queries.items()}

    cat = results["accuracy_by_category"]
    bar_chart(cat, "category", "exact_match_pct", "Count accuracy by category (exact match)",
              "% of counts matching system", "accuracy_by_category.png", highlight=cat.iloc[0]["category"])

    shift = results["accuracy_by_shift"]
    bar_chart(shift, "shift", "exact_match_pct", "Count accuracy by shift (exact match)",
              "% of counts matching system", "accuracy_by_shift.png", highlight=shift.iloc[0]["shift"])

    cat_d = cat.sort_values("shrink_dollars")
    fig, ax = plt.subplots(figsize=(7, 4))
    bars = ax.barh(cat_d["category"], cat_d["shrink_dollars"], color=BLUE)
    ax.bar_label(bars, labels=[f"${v:,.0f}" for v in cat_d["shrink_dollars"]], padding=3)
    ax.set_title("Shrink (counted below system) in dollars, by category", loc="left", fontweight="bold")
    ax.set_xlabel("Shrink value, $")
    ax.set_xlim(0, cat_d["shrink_dollars"].max() * 1.18)
    fig.tight_layout()
    fig.savefig(CHARTS / "shrink_dollars_by_category.png", dpi=150)
    plt.close(fig)

    monthly = results["monthly_trend"]
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(monthly["month"], monthly["exact_match_pct"], color=BLUE, marker="o", linewidth=2)
    ax.set_title("Monthly count accuracy (exact match)", loc="left", fontweight="bold")
    ax.set_ylabel("% of counts matching system")
    ax.set_ylim(60, 100)
    plt.setp(ax.get_xticklabels(), rotation=45, ha="right")
    fig.tight_layout()
    fig.savefig(CHARTS / "monthly_accuracy_trend.png", dpi=150)
    plt.close(fig)

    lines = ["# Results (generated by analysis.py)\n"]
    for name, df in results.items():
        lines += [f"## {name}\n", md_table(df), ""]
    (HERE / "results.md").write_text("\n".join(lines))
    print("Wrote charts/ and results.md")


if __name__ == "__main__":
    main()
