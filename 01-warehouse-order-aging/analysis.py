"""Run the SQL in queries.sql against orders.csv, save charts, and write results.md.

Run:  python analysis.py
"""
import re
import sqlite3
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

HERE = Path(__file__).parent
CHARTS = HERE / "charts"
BLUE, ORANGE, GREY = "#1F3A5F", "#D9822B", "#9AA5B1"
plt.rcParams.update({"axes.spines.top": False, "axes.spines.right": False, "font.size": 10})


def load_queries(path: Path) -> dict:
    """Split queries.sql into {name: sql} using the '-- name:' markers."""
    text = path.read_text()
    parts = re.split(r"^-- name:\s*(\w+)\s*$", text, flags=re.MULTILINE)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}


def md_table(df: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    divider = "|" + "|".join(["---"] * len(df.columns)) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([header, divider, *rows])


def bar_chart(df, x, y, title, ylabel, filename, highlight=None):
    fig, ax = plt.subplots(figsize=(7, 4))
    colors = [ORANGE if (highlight and v == highlight) else BLUE for v in df[x]]
    bars = ax.bar(df[x], df[y], color=colors)
    ax.bar_label(bars, fmt="%.1f%%", padding=3)
    ax.set_title(title, loc="left", fontweight="bold")
    ax.set_ylabel(ylabel)
    ax.set_ylim(0, df[y].max() * 1.2)
    fig.tight_layout()
    fig.savefig(CHARTS / filename, dpi=150)
    plt.close(fig)


def main() -> None:
    CHARTS.mkdir(exist_ok=True)
    conn = sqlite3.connect(":memory:")
    pd.read_csv(HERE / "data" / "orders.csv").to_sql("orders", conn, index=False)
    queries = load_queries(HERE / "queries.sql")
    results = {name: pd.read_sql_query(sql, conn) for name, sql in queries.items()}

    by_zone = results["late_by_zone"]
    bar_chart(by_zone, "zone", "late_rate_pct", "Late shipment rate by zone",
              "% of shipped orders late", "late_rate_by_zone.png", highlight=by_zone.iloc[0]["zone"])

    by_day = results["late_by_order_weekday"]
    worst_day = by_day.loc[by_day["late_rate_pct"].idxmax(), "order_weekday"]
    bar_chart(by_day, "order_weekday", "late_rate_pct", "Late shipment rate by day the order was placed",
              "% of shipped orders late", "late_rate_by_weekday.png", highlight=worst_day)

    # Drop the first and last weeks: both are partial weeks at the edges of the data window.
    weekly = results["weekly_trend"].iloc[1:-1]
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(pd.to_datetime(weekly["week_start"]), weekly["late_rate_pct"], color=BLUE, linewidth=2)
    ax.set_title("Weekly late shipment rate (by week orders were placed)", loc="left", fontweight="bold")
    ax.set_ylabel("% late")
    ax.set_ylim(bottom=0)
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(CHARTS / "weekly_late_rate.png", dpi=150)
    plt.close(fig)

    aging = results["open_order_aging"].set_index("zone")[["0-1 days", "2-3 days", "4+ days"]]
    fig, ax = plt.subplots(figsize=(7, 4))
    aging.plot(kind="bar", stacked=True, ax=ax, color=[GREY, ORANGE, "#B23A48"], rot=0)
    ax.set_title("Open (unshipped) orders by age at 2025-06-30", loc="left", fontweight="bold")
    ax.set_ylabel("Open orders")
    ax.set_xlabel("")
    ax.set_ylim(0, aging.sum(axis=1).max() * 1.12)
    ax.legend(title="Order age", frameon=False)
    fig.tight_layout()
    fig.savefig(CHARTS / "open_order_aging.png", dpi=150)
    plt.close(fig)

    lines = ["# Results (generated by analysis.py)\n"]
    for name, df in results.items():
        lines += [f"## {name}\n", md_table(df), ""]
    (HERE / "results.md").write_text("\n".join(lines))
    print("Wrote charts/ and results.md")


if __name__ == "__main__":
    main()
